function textLen(html) {
  return html.replace(/<[^>]+>/g, "").replace(/\s+/g, " ").trim().length;
}

// ── 1. 기존 아티클 확장 ──
for (const file of fs.readdirSync(ARTICLES_DIR).filter((f) => f.endsWith(".json"))) {
  const p = path.join(ARTICLES_DIR, file);
  const article = JSON.parse(fs.readFileSync(p, "utf8"));
  if (article.contentHtml.includes(MARKER)) continue;

  const supplement = CATEGORY_SUPPLEMENT[article.category];
  if (!supplement) {
    console.warn("no supplement for category", article.category, article.slug);
    continue;
  }

  article.contentHtml += supplement;
  if (!article.author) article.author = "머니깨비 편집팀";
  fs.writeFileSync(p, JSON.stringify(article, null, 2) + "\n", "utf8");
  console.log("expanded", article.slug, "->", textLen(article.contentHtml));
}

